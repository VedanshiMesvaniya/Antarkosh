"""``semantics/column_dictionary.json``: the generated meaning cards (auto-schema Phase 9b).

Layout: ``{"generated_by": "auto_column_meaning", "prompt_version": N, "tables": {<table>: {"evidence_hash": ..., "columns": {<column>: card}}}}``.
A table's cards are reused as long as its ``evidence_hash`` and the prompt version are unchanged, so a second sync makes no
model calls for a table nobody touched.

Same safety rules as every generated file: ``erp_main`` is never read or written, only a missing file or one this phase
generated is replaced, the write is atomic and skipped when nothing changed.

Origin: new (no previous file)
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from src.sql import registry
from src.sql.knowledge.loaders import DEFAULT_DB_ID, validate_db_id
from src.sql.semantics.meaning import PROMPT_VERSION

GENERATED_BY = "auto_column_meaning"
DICTIONARY_REL = "semantics/column_dictionary.json"


def _folder(db_id: str, databases_dir: Path | None) -> Path:
    return (Path(databases_dir) if databases_dir is not None else registry.DATABASES_DIR) / db_id


def read_dictionary(db_id: str, databases_dir: Path | None = None) -> tuple[str, dict[str, Any]]:
    """``("missing" | "ours" | "foreign", document)``. A file that is not this phase's, or cannot be read, is "foreign"."""
    path = _folder(db_id, databases_dir) / DICTIONARY_REL
    if not path.exists():
        return "missing", empty_document()
    try:
        doc = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return "foreign", empty_document()
    if isinstance(doc, dict) and doc.get("generated_by") == GENERATED_BY and isinstance(doc.get("tables"), dict):
        return "ours", doc
    return "foreign", empty_document()


def empty_document() -> dict[str, Any]:
    return {"generated_by": GENERATED_BY, "version": 1, "prompt_version": PROMPT_VERSION, "tables": {}}


def is_current(entry: Any, evidence_hash: str, doc: dict[str, Any]) -> bool:
    """A table's cards are up to date: same evidence, same prompt, and the cards are there."""
    return (
        isinstance(entry, dict)
        and entry.get("evidence_hash") == evidence_hash
        and doc.get("prompt_version") == PROMPT_VERSION
        and isinstance(entry.get("columns"), dict)
    )


def content_key(doc: dict[str, Any]) -> str:
    """What the file means, without timestamps: used to skip a write that would change nothing."""
    return json.dumps({"p": doc.get("prompt_version"), "t": doc.get("tables")}, sort_keys=True)


def write_dictionary(db_id: str, doc: dict[str, Any], databases_dir: Path | None = None) -> dict[str, Any]:
    """Returns ``{"written": bool, "unchanged": bool, "skipped": str | None}``."""
    validate_db_id(db_id)
    out: dict[str, Any] = {"written": False, "unchanged": False, "skipped": None}
    if db_id == DEFAULT_DB_ID:
        out["skipped"] = "pinned database: curated files are never replaced"
        return out
    folder = _folder(db_id, databases_dir)
    if not folder.is_dir():
        out["skipped"] = "database folder does not exist"
        return out
    state, current = read_dictionary(db_id, databases_dir)
    if state == "foreign":
        out["skipped"] = "a file not generated by auto_column_meaning is present; left untouched"
        return out
    if state == "ours" and content_key(current) == content_key(doc):
        out["unchanged"] = True
        return out
    doc = {**doc, "generated_at": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")}
    registry.atomic_write_json(folder / DICTIONARY_REL, doc, mode=0o644)
    out["written"] = True
    return out


__all__ = ["DICTIONARY_REL", "GENERATED_BY", "content_key", "empty_document", "is_current", "read_dictionary", "write_dictionary"]
