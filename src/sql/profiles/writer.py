"""The table-profiles file (auto-schema Phase 7): ``databases/<db_id>/schema/table_profiles.json``.

Safety rules, each enforced here and tested:

* ``erp_main`` is never read or written.
* The folder must already exist; this module never creates a database folder.
* Only a missing file, or one this phase generated (``"generated_by": "auto_table_profiles"``), is replaced. Anything
  else in that place is treated as curated and left untouched.
* The write is atomic, and skipped when nothing that feeds the file has changed since the last write.
* Prompts do not read this file yet (it is consumed in Phase 12, in shadow mode first), so no prompt cache needs clearing.

Origin: new (no previous file)
"""

from __future__ import annotations

import hashlib
import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from src.sql import registry
from src.sql.knowledge.loaders import DEFAULT_DB_ID, validate_db_id
from src.sql.profiles.authority import RULESET_VERSION, ProfileSet, summary
from src.sql.relationships.model import CatalogGraph

GENERATED_BY = "auto_table_profiles"
PROFILES_REL = "schema/table_profiles.json"
INFERRED_REL = "schema/inferred_relationships.json"


def input_key(graph: CatalogGraph, inferred_key: str | None) -> str:
    """Changes only when something that would change the file changes. Timestamps are not part of it."""
    raw = json.dumps([graph.inputs_hash, RULESET_VERSION, inferred_key])
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()[:16]


def _entry(p: Any) -> dict[str, Any]:
    entry: dict[str, Any] = {
        "name": p.name, "schema": p.schema, "kind": p.kind, "tags": list(p.tags), "tag_basis": p.tag_basis,
        "group": p.group, "authority": p.authority, "preferred": p.preferred, "confidence": p.confidence,
    }
    if p.signals is not None:
        s = p.signals
        entry["score"] = p.score
        entry["signals"] = {
            "copy_marker": s.marker, "referenced_by": s.referenced_by, "procedure_use": s.procedure_use,
            "row_estimate": s.rows, "has_primary_key": s.has_primary_key, "declared_fk_out": s.declared_fk_out,
        }
    return entry


def profiles_document(graph: CatalogGraph, result: ProfileSet, key: str) -> dict[str, Any]:
    return {
        "generated_by": GENERATED_BY,
        "generated_at": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "note": "One profile per table and view; nothing is hidden. Tags come from copy words in names; 'authority' says which of "
                "several similar tables holds the real data (a primary is named only when the evidence clearly separates them). "
                "Advisory only: prompts do not read this file yet.",
        "input_key": key,
        "inputs_hash": graph.inputs_hash,
        "ruleset_version": RULESET_VERSION,
        "stats": summary(result),
        "groups": [
            {"id": g.id, "kind": g.kind, "members": list(g.members), "primary": g.primary, "confidence": g.confidence, "lead": g.lead}
            for g in sorted(result.groups, key=lambda g: g.id)
        ],
        "tables": {q: _entry(result.profiles[q]) for q in sorted(result.profiles)},
    }


def _read(path: Path) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def write_profiles_file(
    db_id: str,
    graph: CatalogGraph,
    result: ProfileSet,
    *,
    inferred_key: str | None = None,
    databases_dir: Path | None = None,
) -> dict[str, Any]:
    """Write ``schema/table_profiles.json``. Returns ``{"written": bool, "unchanged": bool, "skipped": str | None}``."""
    validate_db_id(db_id)
    out: dict[str, Any] = {"written": False, "unchanged": False, "skipped": None}
    if db_id == DEFAULT_DB_ID:
        out["skipped"] = "pinned database: curated files are never replaced"
        return out
    folder = (Path(databases_dir) if databases_dir is not None else registry.DATABASES_DIR) / db_id
    if not folder.is_dir():
        out["skipped"] = "database folder does not exist"
        return out
    path = folder / PROFILES_REL
    key = input_key(graph, inferred_key)
    if path.exists():
        existing = _read(path)
        if not (isinstance(existing, dict) and existing.get("generated_by") == GENERATED_BY):
            out["skipped"] = "a file not generated by auto_table_profiles is present; left untouched"
            return out
        if existing.get("input_key") == key:
            out["unchanged"] = True
            return out
    registry.atomic_write_json(path, profiles_document(graph, result, key), mode=0o644)
    out["written"] = True
    return out


__all__ = ["GENERATED_BY", "INFERRED_REL", "PROFILES_REL", "input_key", "profiles_document", "write_profiles_file"]
